def clean_float(val):
    """
    Cleans descriptor values into a float or None.
    Handles legacy R missingness encodings like 'Not Available', 'NA', 'null', '?', or nan.
    """
    if val is None:
        return None
    # Unpack nested list or array values to get scalar float
    while hasattr(val, '__len__') and not isinstance(val, (str, bytes, dict)):
        if len(val) == 0:
            return None
        val = val[0]

    if isinstance(val, (int, float)):
        if np.isnan(val):
            return None
        return float(val)
    # If it's a string, strip and match common missingness placeholders
    s_val = str(val).strip()
    if s_val.lower() in ("not available", "na", "null", "none", "?", "", "nan"):
        return None
    try:
        return float(s_val)
    except ValueError:
        return None

def clean_array(arr):
    """
    Cleans signal/coordinate arrays into 1D float numpy arrays.
    Gracefully handles string arrays, converting 'Not Available' to NaN.
    """
    if arr is None:
        return None
    arr = np.array(arr).ravel()
    try:
        return arr.astype(float)
    except ValueError:
        cleaned = []
        for x in arr:
            cleaned.append(clean_float(x))
        return np.array([x if x is not None else np.nan for x in cleaned], dtype=float)

def clean_timestamp(val):
    """
    Parses dynamic date strings from .Resi files into Python datetime objects.
    """
    if val is None or pd.isna(val):
        return None
    # Unpack nested list or array values to get scalar timestamp
    while hasattr(val, '__len__') and not isinstance(val, (str, bytes, dict)):
        if len(val) == 0:
            return None
        val = val[0]

    if isinstance(val, (datetime, pd.Timestamp)):
        return val.to_pydatetime() if hasattr(val, 'to_pydatetime') else val
    s_val = str(val).strip()
    if s_val.lower() in ("not available", "na", "null", "none", "?", ""):
        return None
    # Try common formats
    for fmt in (
        "%Y-%m-%d %H:%M:%S",
        "%Y-%m-%d %H:%M",
        "%m/%d/%Y %H:%M:%S",
        "%m/%d/%Y %H:%M",
        "%d/%m/%Y %H:%M:%S",
        "%d/%m/%Y %H:%M",
        "%Y/%m/%d %H:%M:%S",
        "%Y/%m/%d %H:%M"
    ):
        try:
            return datetime.strptime(s_val, fmt)
        except ValueError:
            continue
    try:
        dt = pd.to_datetime(s_val, dayfirst=True)
        if pd.isna(dt):
            return None
        return dt.to_pydatetime()
    except Exception:
        return None

DUCKDB_PREFIX_RE = re.compile(r'^[A-Za-z_][A-Za-z0-9_]*$')


def duckdb_table_names(table_prefix=""):
    """Table names used by to_duckdb/from_duckdb for a given prefix.

    The names are interpolated into SQL, so the prefix must be a plain
    identifier prefix: anything else raises ValueError.
    """
    if table_prefix and not DUCKDB_PREFIX_RE.match(table_prefix):
        raise ValueError(f"table_prefix must contain only letters, digits and underscores: {table_prefix!r}")
    return tuple(f"{table_prefix}{t}" for t in ('traces', 'results', 'rings', 'boards'))


def get_rpm_coef_params(rpm_coef):
    """
    Extracts the standard 'a' and 'b' calibration coefficients from an RPMCoef column.
    Defaults to a=-0.8, b=1.0 if not specified.
    """
    if rpm_coef is None:
        return -0.8, 1.0
    # Unpack nested list or array values to get scalar coefficient
    while hasattr(rpm_coef, '__len__') and not isinstance(rpm_coef, (str, bytes, dict)):
        if len(rpm_coef) == 0:
            return -0.8, 1.0
        rpm_coef = rpm_coef[0]

    if isinstance(rpm_coef, (int, float)):
        if np.isnan(rpm_coef):
            return -0.8, 1.0
        return float(rpm_coef), 1.0
    if isinstance(rpm_coef, dict):
        a = rpm_coef.get('a', rpm_coef.get('RPMCoef.a', -0.8))
        b = rpm_coef.get('b', rpm_coef.get('RPMCoef.b', 1.0))
        return float(a), float(b)
    # Check attributes if it is a custom R list object
    a = getattr(rpm_coef, 'a', getattr(rpm_coef, 'RPMCoef_a', -0.8))
    b = getattr(rpm_coef, 'b', getattr(rpm_coef, 'RPMCoef_b', 1.0))
    return float(a), float(b)

def nonlinear_baseline_correction(a_mm, k, b, d, f):
    """
    Sigmoidal rise -> linear continuation baseline correction function.
    Matches the FQResi R implementation of NonlinearBaslineCorrection.
    """
    a = a_mm * 10.0  # Convert mm to 0.1mm units
    norm_const = 1.0 - 2.0 / (1.0 + np.exp(k * a / 2.0))

    # Calculate linear continuation slope (m)
    m = f / (d - a) if d > a else 0.0
    x_vals = np.linspace(0, d, d)

    # Piecewise unified function
    sigmoid_y = (b / (1.0 + np.exp(-k * (x_vals - a / 2.0))) - b / (1.0 + np.exp(k * a / 2.0))) / norm_const
    linear_y = b + m * (x_vals - a)

    curve_y = np.where(x_vals <= a, sigmoid_y, linear_y)
    return curve_y - b

def area_weight_radius(anarray):
    """
    Computes the area weighted Pith-to-Bark trace.
    Matches the FQResi R function Area_Weight_Radius.
    """
    anarray = np.array(anarray)
    length = len(anarray)
    if length == 0:
        return anarray
    x = np.arange(1, length + 1)
    y = np.sqrt(x) / np.pi
    y_area = (y / np.max(y) * length)

    # Floor indexing match to R's float-to-int conversion logic
    indices = np.clip((y_area).astype(int) - 1, 0, length - 1)
    return anarray[indices]


class ResiResult:
    """
    Represents a single drilling trace record and its associated metrics/signals.
    """
    def __init__(self, filename, descriptors, drill=None, feed=None, rpos=None, ring_data=None, board_moe=None, resi_file=None, rs_row=None):
        self.FileName = filename
        self.descriptors = descriptors or {}

        # Raw signals and annotations
        self.drill = drill
        self.feed = feed
        self.rPos = rpos

        # Associated tabular data lists (list of dicts)
        self.ring_data = ring_data or []
        self.board_moe = board_moe or []
        self.rs_row = rs_row or {}

        # Metadata
        self.ResiFile = resi_file

        # Placeholders for stored intermediate traces (if available in Resi file)
        self.den_trace = None
        self.cum_den_trace = None
        self.corr_trace = None

    @property
    def TraceHash(self):
        """
        Unique SHA-256 hash derived from the raw drill and feed data.
        """
        h = hashlib.sha256()
        if self.drill is not None:
            h.update(self.drill.tobytes())
        if self.feed is not None:
            h.update(self.feed.tobytes())
        return h.hexdigest()

    def __getattr__(self, name):
        """
        Fallback accessor for descriptor keys, providing case-insensitive lookup.
        """
        # private/dunder names and descriptors itself must fail normally, or
        # copy/pickle (which run before __init__) recurse forever
        if name.startswith('_') or name == 'descriptors':
            raise AttributeError(f"'{self.__class__.__name__}' object has no attribute '{name}'")
        # Exact match check
        if name in self.descriptors:
            return self.descriptors[name]
        # Case-insensitive match check
        for k, v in self.descriptors.items():
            if k.lower() == name.lower():
                return v
        if name.upper() in ("DOB", "DBHOB"):
            alt_key = "DBHOB" if name.upper() == "DOB" else "DOB"
            for k, v in self.descriptors.items():
                if k.lower() == alt_key.lower():
                    return v
        raise AttributeError(f"'{self.__class__.__name__}' object has no attribute '{name}'")

    def get_descriptor(self, name, default=None):
        """
        Gets a descriptor value case-insensitively with key alias resolution. Returns default if not found.
        """
        if name in self.descriptors:
            return self.descriptors[name]
        for k, v in self.descriptors.items():
            if k.lower() == name.lower():
                return v
        if name.upper() in ("DOB", "DBHOB"):
            alt_key = "DBHOB" if name.upper() == "DOB" else "DOB"
            for k, v in self.descriptors.items():
                if k.lower() == alt_key.lower():
                    return v
        return default

    def _trace_standardise(self, tr, RPMCoef=None):
        """
        Standardizes raw drill trace torque values to constant sampling conditions (firmware < 5).
        """
        standardised_flag = self.descriptors.get('Standardised', True)
        if standardised_flag in ("FALSE", "F", False):
            return tr.copy()
        if self.descriptors.get('ResiCode') == "RinnTech":
            return tr.copy()

        feed_speed = float(self.descriptors.get('FeedSpeed', 2000.0) or 2000.0)
        rpm = float(self.descriptors.get('RPM', 2500.0) or 2500.0)

        FRcoef = (feed_speed * 0.00032624) + 0.34495
        x = 2500.0 / rpm

        a, b = get_rpm_coef_params(self.descriptors.get('RPMCoef') if RPMCoef is None else RPMCoef)
        RPMcoef = a * np.log(x) + b

        stCoef = FRcoef / RPMcoef
        return tr / stCoef

    def _trace_standardise_v5(self, tr):
        """
        Standardizes raw drill trace torque values using firmware 5+ chip size equations.
        """
        standardised_flag = self.descriptors.get('Standardised', True)
        if standardised_flag in ("FALSE", "F", False):
            return tr.copy()
        if self.descriptors.get('ResiCode') == "RinnTech":
            return tr.copy()

        feed_speed = float(self.descriptors.get('FeedSpeed', 2000.0) or 2000.0)
        rpm = float(self.descriptors.get('RPM', 2500.0) or 2500.0)
        cs = feed_speed / (2.0 * rpm)
        cs_std = 0.4

        resource = self.descriptors.get('Resource', 'Other')

        # Softwood vs Hardwood coefficients
        if resource in ("HoopPine", "MediumDensitySoftwood"):
            c1, c2 = 58.0, 0.6
        elif resource == "RadiataPine":
            c1, c2 = 68.0, 0.57
        elif resource == "SouthernPine":
            c1, c2 = 73.0, 0.63
        elif resource == "HighDensitySoftwood":
            c1, c2 = 102.0, 0.57
        elif resource in ("Enitens", "Eglobulus", "PlantationTeak", "MediumDensityHardwood"):
            c1, c2 = 83.0, 0.48
        elif resource == "CCV":
            c1, c2 = 104.0, 0.48
        elif resource == "HighDensityHardwood":
            c1, c2 = 94.9, 0.45
        else:
            c1, c2 = 68.0, 0.57

        ampl_std = c1 * (cs_std ** c2)
        ampl = c1 * (cs ** c2)
        stCoef = ampl / ampl_std
        return tr / stCoef

    def recompute_corr_trace(self, RPMCoef=None):
        """
        Recomputes the needle-drag corrected amplitude/torque trace (corrTrace).
        """
        if self.drill is None:
            return None

        tr = self.drill.astype(float)

        # Check firmware version format to select standardization function
        version = self.descriptors.get('Version', '')
        version_num = 0
        if version and len(version) >= 9:
            try:
                version_num = int(version[8])
            except ValueError:
                pass

        if version_num >= 5:
            std_trace = self._trace_standardise_v5(tr)
        else:
            std_trace = self._trace_standardise(tr, RPMCoef)

        dob = self.descriptors.get('DOB', 0) or 0
        obdia = int(min(len(std_trace) - 15, dob * 10))
        if obdia <= 0:
            obdia = len(std_trace)

        baseline_method = self.descriptors.get('BaselineMethod', 'Linear')
        if self.TraceType == "CAL":
            baseline_method = "None"

        BLCorrDen = float(self.descriptors.get('BLCorrDen', 0.0) or 0.0)

        if baseline_method == "None":
            return std_trace[:obdia]
        elif baseline_method == "Linear":
            bCorr = np.arange(1, obdia + 1) / obdia * BLCorrDen
            return std_trace[:obdia] - bCorr
        elif baseline_method == "NonLinear":
            bark_thickness = float(self.descriptors.get('BarkThickness', 0.0) or 0.0)
            d = obdia - int(bark_thickness * 10)
            if d <= 0:
                d = obdia

            resource = self.descriptors.get('Resource', 'Other')
            if resource in ("RadiataPine", "SouthernPine", "MediumDensitySoftwood"):
                b_offset = 2.0
            elif resource == "HoopPine":
                b_offset = 1.5
            elif resource in ("Enitens", "Eglobulus", "Eucalypt", "MediumDensityHardwood"):
                b_offset = 6.0
            else:
                b_offset = 2.0

            a_val = 40.0  # mm
            k_val = 0.03

            nonlin_corr = nonlinear_baseline_correction(a_val, k_val, b_offset, d, BLCorrDen)

            entry_bark_len = int(bark_thickness * 10)
            bCorr = np.concatenate([np.zeros(entry_bark_len), nonlin_corr])

            if len(bCorr) < obdia:
                bCorr = np.pad(bCorr, (0, obdia - len(bCorr)), 'edge')
            else:
                bCorr = bCorr[:obdia]

            return std_trace[:obdia] - bCorr
        else:
            return std_trace[:obdia]

    def recompute_den_trace(self, RPMCoef=None):
        """
        Recomputes the density trace (denTrace) by standardizing, correcting baseline, and calibrating.
        """
        c_trace = self.recompute_corr_trace(RPMCoef)
        if c_trace is None:
            return None

        eqn_type = self.descriptors.get('EqnType', 'Linear')
        r_slope = float(self.descriptors.get('rSlope', 1.0) or 1.0)
        r_intcpt = float(self.descriptors.get('rIntcpt', 0.0) or 0.0)

        if eqn_type == "Linear":
            return c_trace * r_slope + r_intcpt
        elif eqn_type == "Ln":
            bark_thickness = float(self.descriptors.get('BarkThickness', 0.0) or 0.0)
            s = int(max(1, bark_thickness * 10))

            if self.TraceType == "P-B":
                entry_radius = float(self.descriptors.get('EntryRadius', 0.0) or 0.0)
                f = int(entry_radius * 10)
            else:
                ubdia = float(self.descriptors.get('UBDIA', 0.0) or 0.0)
                f = int(ubdia * 10 + s)

            if f <= s or f > len(c_trace):
                f = len(c_trace)

            sub_trace = c_trace[s:f]
            mean_torque = np.mean(sub_trace) if len(sub_trace) > 0 else 1.0
            if mean_torque <= 0.0:
                mean_torque = 1.0

            mean_density = np.log(mean_torque) * r_slope + r_intcpt
            return c_trace / mean_torque * mean_density
        else:
            return c_trace * r_slope + r_intcpt

    def recompute_cum_den_trace(self, RPMCoef=None):
        """
        Recomputes the area-weighted cumulative density trace.
        """
        den_trace = self.recompute_den_trace(RPMCoef)
        if den_trace is None:
            return None

        bark_thickness = float(self.descriptors.get('BarkThickness', 0.0) or 0.0)
        entry_radius = float(self.descriptors.get('EntryRadius', 0.0) or 0.0)
        s = int(bark_thickness * 10)
        f = int(entry_radius * 10)

        if f <= s or f > len(den_trace):
            f = len(den_trace)

        entry_den = den_trace[s:f]
        if len(entry_den) == 0:
            return np.array([])

        aw_entry = area_weight_radius(entry_den)
        return np.cumsum(aw_entry) / np.arange(1, len(aw_entry) + 1)


def normalize_filepath(filepath):
    """
    Normalizes file paths across URI schemes (file:, abfss:), /lakehouse/default mount points,
    and relative Fabric Lakehouse paths.
    """
    if filepath is None:
        return None

    path_str = str(filepath)

    # Handle file: / file:// URIs
    if path_str.startswith("file://"):
        path_str = path_str[7:]
    elif path_str.startswith("file:"):
        path_str = path_str[5:]

    # Handle abfss: / abfss:// URIs
    if path_str.startswith("abfss://"):
        parts = path_str.split("onelake.dfs.fabric.microsoft.com/")
        if len(parts) > 1:
            sub_parts = parts[1].split("/", 1)
            if len(sub_parts) > 1:
                path_str = f"/lakehouse/default/{sub_parts[1]}"
            else:
                path_str = f"/lakehouse/default/{parts[1]}"
        else:
            import re
            match = re.search(r"abfss://[^/]+/[^/]+/(.*)", path_str)
            if match:
                path_str = f"/lakehouse/default/{match.group(1)}"
            else:
                clean_path = path_str[8:].lstrip('/')
                if not clean_path.startswith("lakehouse/"):
                    path_str = f"/lakehouse/default/{clean_path}"
                else:
                    path_str = f"/{clean_path}"
    elif path_str.startswith("abfss:"):
        clean_path = path_str[6:].lstrip('/')
        if not clean_path.startswith("lakehouse/"):
            path_str = f"/lakehouse/default/{clean_path}"
        else:
            path_str = f"/{clean_path}"

    # Handle Fabric relative Lakehouse paths like Files/... or Tables/...
    if (
        path_str.startswith("Files/")
        or path_str.startswith("Tables/")
        or path_str.startswith("files/")
        or path_str.startswith("tables/")
    ):
        path_str = f"/lakehouse/default/{path_str}"

    return Path(path_str)


class ResiResultSet:
    """
    Represents a collection of ResiResult objects.
    """
    def __init__(self, dotresi_filepaths=None):
        self.results = []
        self.version_info = {}

        if dotresi_filepaths:
            if isinstance(dotresi_filepaths, (str, Path)):
                dotresi_filepaths = [dotresi_filepaths]
            for path in dotresi_filepaths:
                self.load(path)

    def load(self, filepath):
        """
        Loads and appends traces and results from a .Resi file.
        """
        filepath = normalize_filepath(filepath)
        if not filepath.exists():
            raise FileNotFoundError(f"File not found: {filepath}")

        with warnings.catch_warnings():
            warnings.simplefilter("ignore")
            parsed = rdata.parser.parse_file(str(filepath))
            converted = rdata.conversion.convert(parsed)

        converted = {str(k): v for k, v in converted.items()}
        df = converted.get('df')
        if df is None:
            raise ValueError(f"Missing 'df' key in .Resi file {filepath}")

        res_traces = converted.get('resTraces')
        feed_traces = converted.get('feedTraces')
        r_pos_list = converted.get('rPos')
        ring_data_df = converted.get('ringData')
        board_moe_df = converted.get('boardMOE')
        rs_df = converted.get('RSdf')
        fr_df = converted.get('FRdf')

        def clean_df(rdf):
            if rdf is None or not isinstance(rdf, pd.DataFrame):
                return rdf
            rdf = rdf.copy()
            rdf.columns = [str(c) for c in rdf.columns]
            return rdf

        df = clean_df(df)
        ring_data_df = clean_df(ring_data_df)
        board_moe_df = clean_df(board_moe_df)
        rs_df = clean_df(rs_df)
        fr_df = clean_df(fr_df)

        version_obj = converted.get('version')
        version_str = "Unknown"
        if version_obj is not None:
            if isinstance(version_obj, np.ndarray) and len(version_obj) > 0:
                version_str = str(version_obj[0])
            elif isinstance(version_obj, dict) and 'version.string' in version_obj:
                version_str = str(version_obj['version.string'][0])
            else:
                version_str = str(version_obj)

        # Columns to clean/coerce to floats/None
        num_cols = (
            'FeedSpeed', 'RPM', 'OffsetDrill', 'OffsetFeed', 'Lat', 'Lon',
            'DOB', 'UBDIA', 'BarkThickness', 'ExitBarkThickness', 'DiscArea',
            'PrAWV', 'PrMOE', 'OWDensity', 'CoreDensity', 'DiscDensity',
            'EntryRadius', 'EntryDensity', 'ExitRadius', 'ExitDensity',
            'Decay', 'RingCount', 'BLCorrDen', 'rSlope', 'rIntcpt', 'RPMCoef'
        )

        def find_trace_item(trace_container, idx, fname):
            if trace_container is None:
                return None
            if isinstance(trace_container, dict):
                if fname in trace_container:
                    return trace_container[fname]
                for k, v in trace_container.items():
                    if str(k).lower() == str(fname).lower():
                        return v
                    if Path(str(k)).stem.lower() == Path(str(fname)).stem.lower():
                        return v
            elif isinstance(trace_container, (list, tuple)):
                if idx < len(trace_container):
                    return trace_container[idx]
            return None

        # Pre-group nested DataFrames by FileName for O(1) instantaneous lookup
        ring_dict = {}
        if isinstance(ring_data_df, pd.DataFrame) and not ring_data_df.empty and 'FileName' in ring_data_df.columns:
            for fn, group in ring_data_df.groupby('FileName'):
                matched = group.to_dict(orient='records')
                for r_dct in matched:
                    for k in list(r_dct.keys()):
                        if k not in ('Radius', 'FileName', 'TreeID', 'ResiCode'):
                            r_dct[k] = clean_float(r_dct[k])
                ring_dict[str(fn)] = matched

        board_dict = {}
        if isinstance(board_moe_df, pd.DataFrame) and not board_moe_df.empty and 'FileName' in board_moe_df.columns:
            for fn, group in board_moe_df.groupby('FileName'):
                matched = group.to_dict(orient='records')
                for b_dct in matched:
                    for k in list(b_dct.keys()):
                        if k not in ('FileName', 'TreeID'):
                            b_dct[k] = clean_float(b_dct[k])
                board_dict[str(fn)] = matched

        rs_dict = {}
        if isinstance(rs_df, pd.DataFrame) and not rs_df.empty and 'FileName' in rs_df.columns:
            for fn, group in rs_df.groupby('FileName'):
                if not group.empty:
                    r_row = group.iloc[0].to_dict()
                    for k in list(r_row.keys()):
                        if k not in ('FileName', 'TreeID', 'select'):
                            r_row[k] = clean_float(r_row[k])
                    rs_dict[str(fn)] = r_row

        # Build ResiResult entries
        for i in range(len(df)):
            row = df.iloc[i]
            descriptors = row.to_dict()

            # Map legacy spelling typos case-insensitively
            sample_date_val = None
            sample_date_key = None
            for k in list(descriptors.keys()):
                if k.lower() in ('sampledate', 'sampledata'):
                    sample_date_val = descriptors[k]
                    sample_date_key = k
                    break
            if sample_date_key is not None:
                descriptors['SampleDate'] = clean_timestamp(sample_date_val)
                if sample_date_key != 'SampleDate':
                    descriptors.pop(sample_date_key, None)

            # Real files carry both DBHOB (often all NA) and DOB: keep both,
            # and only fall back to DBHOB for DOB when DOB is missing
            dob_keys = {k.lower(): k for k in descriptors if k.lower() in ('dob', 'dbhob')}
            dob_val = clean_float(descriptors[dob_keys['dob']]) if 'dob' in dob_keys else None
            dbhob_val = clean_float(descriptors[dob_keys['dbhob']]) if 'dbhob' in dob_keys else None
            for k in dob_keys.values():
                descriptors.pop(k)
            if 'dbhob' in dob_keys:
                descriptors['DBHOB'] = dbhob_val
            if dob_keys:
                descriptors['DOB'] = dob_val if dob_val is not None else dbhob_val

            # Clean/coerce numeric columns case-insensitively
            for col in num_cols:
                if col == 'DOB':
                    continue
                actual_key = None
                if col in descriptors:
                    actual_key = col
                else:
                    for k in descriptors.keys():
                        if k.lower() == col.lower():
                            actual_key = k
                            break
                if actual_key is not None:
                    descriptors[actual_key] = clean_float(descriptors[actual_key])

            filename = descriptors.get('FileName')

            # Fetch signals
            drill = find_trace_item(res_traces, i, filename)
            feed = find_trace_item(feed_traces, i, filename)
            rpos = find_trace_item(r_pos_list, i, filename)

            # O(1) dictionary lookups
            ring_data = ring_dict.get(str(filename), []) if filename else []
            board_moe = board_dict.get(str(filename), []) if filename else []
            rs_row = rs_dict.get(str(filename), {}) if filename else {}

            result = ResiResult(
                filename=filename,
                descriptors=descriptors,
                drill=clean_array(drill),
                feed=clean_array(feed),
                rpos=clean_array(rpos),
                ring_data=ring_data,
                board_moe=board_moe,
                resi_file=str(filepath),
                rs_row=rs_row
            )

            # Parse precomputed arrays if available
            den_traces = converted.get('denTraces')
            cum_den_traces = converted.get('cumDenTraces')
            corr_traces = converted.get('corrTraces')

            result.den_trace = clean_array(find_trace_item(den_traces, i, filename))
            result.cum_den_trace = clean_array(find_trace_item(cum_den_traces, i, filename))
            result.corr_trace = clean_array(find_trace_item(corr_traces, i, filename))

            # --- AUTO-VALIDATION CONTROLS ---
            if result.corr_trace is not None:
                recomputed = result.recompute_corr_trace()
                if recomputed is not None:
                    common_len = min(len(result.corr_trace), len(recomputed))
                    if common_len > 0:
                        mae = np.mean(np.abs(result.corr_trace[:common_len] - recomputed[:common_len]))
                        if mae > 0.05:
                            warnings.warn(
                                f"Discrepancy: Recomputed corrected trace for '{filename}' "
                                f"differs from stored trace in {filepath.name} (MAE={mae:.4f})"
                            )

            if result.den_trace is not None:
                recomputed = result.recompute_den_trace()
                if recomputed is not None:
                    common_len = min(len(result.den_trace), len(recomputed))
                    if common_len > 0:
                        mae = np.mean(np.abs(result.den_trace[:common_len] - recomputed[:common_len]))
                        if mae > 0.05:
                            warnings.warn(
                                f"Discrepancy: Recomputed density trace for '{filename}' "
                                f"differs from stored trace in {filepath.name} (MAE={mae:.4f})"
                            )

            self.results.append(result)

        self.version_info[str(filepath)] = version_str
        return self

    @property
    def df(self):
        """
        Returns a combined pandas DataFrame of descriptors for all results.
        """
        if not self.results:
            return pd.DataFrame()
        return pd.DataFrame([r.descriptors for r in self.results])

    @property
    def ring_data(self):
        """
        Returns a combined pandas DataFrame of annual ring metrics for all results.
        """
        all_rings = []
        for r in self.results:
            for ring in r.ring_data:
                row = {'FileName': r.FileName}
                row.update(ring)
                all_rings.append(row)
        return pd.DataFrame(all_rings)

    @property
    def board_moe(self):
        """
        Returns a combined pandas DataFrame of board MOE metrics for all results.
        """
        all_boards = []
        for r in self.results:
            for board in r.board_moe:
                row = {'FileName': r.FileName}
                row.update(board)
                all_boards.append(row)
        return pd.DataFrame(all_boards)

    def to_duckdb(self, conn_or_path, table_prefix=""):
        """
        Exports the result set records to DuckDB, keeping table normalization.

        table_prefix must be a plain SQL identifier prefix (letters, digits, underscore).
        """
        duckdb_table_names(table_prefix)
        if isinstance(conn_or_path, (str, Path)):
            conn = duckdb.connect(str(conn_or_path))
            close_conn = True
        else:
            conn = conn_or_path
            close_conn = False

        t_traces, t_results, t_rings, t_boards = duckdb_table_names(table_prefix)

        # Create tables
        conn.execute(f"""
            CREATE TABLE IF NOT EXISTS {t_traces} (
                id INTEGER PRIMARY KEY,
                TraceHash VARCHAR UNIQUE,
                InsertTime TIMESTAMP,
                FileName VARCHAR,
                TreeID VARCHAR,
                ResiCode VARCHAR,
                SampleDate TIMESTAMP,
                FeedSpeed DOUBLE,
                RPM DOUBLE,
                OffsetDrill DOUBLE,
                OffsetFeed DOUBLE,
                Lat DOUBLE,
                Lon DOUBLE,
                Comment VARCHAR,
                drill DOUBLE[],
                feed DOUBLE[]
            );
        """)
        conn.execute(f"""
            CREATE TABLE IF NOT EXISTS {t_results} (
                id INTEGER PRIMARY KEY,
                TraceID INTEGER,
                ResiFile VARCHAR,
                TraceType VARCHAR,
                TreeClass VARCHAR,
                DOB DOUBLE,
                UBDIA DOUBLE,
                BarkThickness DOUBLE,
                ExitBarkThickness DOUBLE,
                DiscArea DOUBLE,
                PrAWV DOUBLE,
                PrMOE DOUBLE,
                OWDensity DOUBLE,
                CoreDensity DOUBLE,
                DiscDensity DOUBLE,
                EntryRadius DOUBLE,
                EntryDensity DOUBLE,
                ExitRadius DOUBLE,
                ExitDensity DOUBLE,
                Decay DOUBLE,
                RingCount DOUBLE,
                BLCorrDen DOUBLE,
                rSlope DOUBLE,
                rIntcpt DOUBLE,
                RPMCoef DOUBLE,
                Resource VARCHAR,
                BaselineMethod VARCHAR,
                Standardised BOOLEAN,
                RingMethod VARCHAR,
                WebSite VARCHAR,
                RemoteSha VARCHAR,
                rPos DOUBLE[]
            );
        """)
        conn.execute(f"""
            CREATE TABLE IF NOT EXISTS {t_rings} (
                ResultID INTEGER,
                Radius VARCHAR,
                RingFromPith INTEGER,
                RingFromBark INTEGER,
                RingPosition DOUBLE,
                RingWidth DOUBLE,
                RingDensityMean DOUBLE,
                RingDensityCV DOUBLE,
                RingMOEMean DOUBLE,
                RingMOECV DOUBLE
            );
        """)
        conn.execute(f"""
            CREATE TABLE IF NOT EXISTS {t_boards} (
                ResultID INTEGER,
                BoardIndex INTEGER,
                MeanMOE DOUBLE,
                RadialPositionPct DOUBLE
            );
        """)

        seq_trace = conn.execute(f"SELECT COALESCE(MAX(id), 0) + 1 FROM {t_traces}").fetchone()[0]
        seq_result = conn.execute(f"SELECT COALESCE(MAX(id), 0) + 1 FROM {t_results}").fetchone()[0]

        now = datetime.now()

        # Cache existing trace hashes in a single query for O(1) lookup
        existing_hashes = dict(conn.execute(f"SELECT TraceHash, id FROM {t_traces}").fetchall())

        traces_insert = []
        results_insert = []
        rings_insert = []
        boards_insert = []

        for r in self.results:
            thash = r.TraceHash
            if thash in existing_hashes:
                trace_id = existing_hashes[thash]
                descriptors = r.descriptors
                baseline_method = descriptors.get('BaselineMethod', 'Linear')
                ring_method = descriptors.get('RingMethod', 'Annual')
                r_slope = float(descriptors.get('rSlope', 1.0) or 1.0)
                r_intcpt = float(descriptors.get('rIntcpt', 0.0) or 0.0)
                dob = float(descriptors.get('DOB', 0.0) or 0.0)
                ubdia = float(descriptors.get('UBDIA', 0.0) or 0.0)

                identical_result = conn.execute(f"""
                    SELECT id FROM {t_results}
                    WHERE TraceID = ?
                      AND ABS(COALESCE(rSlope, 0) - ?) < 1e-4
                      AND ABS(COALESCE(rIntcpt, 0) - ?) < 1e-4
                      AND ABS(COALESCE(DOB, 0) - ?) < 1e-4
                      AND ABS(COALESCE(UBDIA, 0) - ?) < 1e-4
                      AND COALESCE(BaselineMethod, '') = ?
                      AND COALESCE(RingMethod, '') = ?
                """, (trace_id, r_slope, r_intcpt, dob, ubdia, str(baseline_method), str(ring_method))).fetchone()

                if identical_result:
                    warnings.warn(
                        f"Skipped duplicate insert: Processing run for '{r.FileName}' "
                        f"with matching parameters already exists in database (TraceID: {trace_id}, ResultID: {identical_result[0]})."
                    )
                    continue
                else:
                    result_id = seq_result
                    seq_result += 1
                    self._accumulate_result_records(result_id, trace_id, r, results_insert, rings_insert, boards_insert)
            else:
                trace_id = seq_trace
                seq_trace += 1
                existing_hashes[thash] = trace_id

                traces_insert.append((
                    trace_id, thash, now, r.FileName, r.get_descriptor('TreeID'), r.get_descriptor('ResiCode'), r.get_descriptor('SampleDate'),
                    r.get_descriptor('FeedSpeed'), r.get_descriptor('RPM'), r.get_descriptor('OffsetDrill'), r.get_descriptor('OffsetFeed'), r.get_descriptor('Lat'), r.get_descriptor('Lon'), r.get_descriptor('Comment'),
                    r.drill if r.drill is not None else None,
                    r.feed if r.feed is not None else None
                ))

                result_id = seq_result
                seq_result += 1

                self._accumulate_result_records(result_id, trace_id, r, results_insert, rings_insert, boards_insert)

        # Batch execute parameter lists inside a single transaction
        conn.execute("BEGIN TRANSACTION;")
        try:
            self._insert_duckdb_rows(conn, t_traces, t_results, t_rings, t_boards,
                                     traces_insert, results_insert, rings_insert, boards_insert)
        except Exception:
            conn.execute("ROLLBACK;")
            if close_conn:
                conn.close()
            raise
        conn.execute("COMMIT;")

        if close_conn:
            conn.close()

    @staticmethod
    def _insert_duckdb_rows(conn, t_traces, t_results, t_rings, t_boards,
                            traces_insert, results_insert, rings_insert, boards_insert):
        if traces_insert:
            conn.executemany(f"""
                INSERT INTO {t_traces} (
                    id, TraceHash, InsertTime, FileName, TreeID, ResiCode, SampleDate,
                    FeedSpeed, RPM, OffsetDrill, OffsetFeed, Lat, Lon, Comment, drill, feed
                ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?);
            """, traces_insert)

        if results_insert:
            conn.executemany(f"""
                INSERT INTO {t_results} (
                    id, TraceID, ResiFile, TraceType, TreeClass, DOB, UBDIA, BarkThickness, ExitBarkThickness,
                    DiscArea, PrAWV, PrMOE, OWDensity, CoreDensity, DiscDensity, EntryRadius, EntryDensity,
                    ExitRadius, ExitDensity, Decay, RingCount, BLCorrDen, rSlope, rIntcpt, RPMCoef, Resource,
                    BaselineMethod, Standardised, RingMethod, WebSite, RemoteSha, rPos
                ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?);
            """, results_insert)

        if rings_insert:
            conn.executemany(f"""
                INSERT INTO {t_rings} (
                    ResultID, Radius, RingFromPith, RingFromBark, RingPosition, RingWidth,
                    RingDensityMean, RingDensityCV, RingMOEMean, RingMOECV
                ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?);
            """, rings_insert)

        if boards_insert:
            conn.executemany(f"""
                INSERT INTO {t_boards} (
                    ResultID, BoardIndex, MeanMOE, RadialPositionPct
                ) VALUES (?, ?, ?, ?);
            """, boards_insert)

    def _accumulate_result_records(self, result_id, trace_id, r, results_insert, rings_insert, boards_insert):
        """
        Helper method to prepare parameter tuples for batch insert into results, rings, and boards tables.
        """
        desc = r.descriptors
        std_flag = desc.get('Standardised', True)
        if isinstance(std_flag, str):
            std_flag = std_flag.upper() not in ("FALSE", "F")

        rpm_coef_val = desc.get('RPMCoef')
        if rpm_coef_val is not None:
            if isinstance(rpm_coef_val, (int, float)):
                rpm_coef_flt = float(rpm_coef_val)
            else:
                a_coef, _ = get_rpm_coef_params(rpm_coef_val)
                rpm_coef_flt = a_coef
        else:
            rpm_coef_flt = -0.8

        resi_file_val = r.FileName or r.get_descriptor('ResiFile') or r.ResiFile

        results_insert.append((
            result_id, trace_id, resi_file_val, r.get_descriptor('TraceType'), r.get_descriptor('TreeClass'), r.get_descriptor('DOB'), r.get_descriptor('UBDIA'), r.get_descriptor('BarkThickness'),
            r.get_descriptor('ExitBarkThickness'), r.get_descriptor('DiscArea'), r.get_descriptor('PrAWV'), r.get_descriptor('PrMOE'), r.get_descriptor('OWDensity'), r.get_descriptor('CoreDensity'), r.get_descriptor('DiscDensity'),
            r.get_descriptor('EntryRadius'), r.get_descriptor('EntryDensity'), r.get_descriptor('ExitRadius'), r.get_descriptor('ExitDensity'), r.get_descriptor('Decay'), r.get_descriptor('RingCount'), r.get_descriptor('BLCorrDen'),
            r.get_descriptor('rSlope'), r.get_descriptor('rIntcpt'), rpm_coef_flt, r.get_descriptor('Resource'), r.get_descriptor('BaselineMethod'), bool(std_flag),
            r.get_descriptor('RingMethod'), r.get_descriptor('WebSite'), r.get_descriptor('RemoteSha'),
            r.rPos if r.rPos is not None else None
        ))

        # Rings insert accumulation
        for ring in r.ring_data:
            ring_den_mean = ring.get('RingDensityMean', ring.get('RingMeanDen'))
            ring_moe_mean = ring.get('RingMOEMean', ring.get('RingMeanMOE'))
            rings_insert.append((
                result_id, ring.get('Radius', 'Entry'), ring.get('RingFromPith'), ring.get('RingFromBark'),
                ring.get('RingPosition'), ring.get('RingWidth'), ring_den_mean, ring.get('RingDensityCV'),
                ring_moe_mean, ring.get('RingMOECV')
            ))

        # Boards insert accumulation
        for idx, board in enumerate(r.board_moe):
            mean_moe = board.get('MeanMOE', board.get('BoardMOE'))
            boards_insert.append((
                result_id, idx + 1, mean_moe, board.get('RadialPositionPct', 0.0)
            ))

    @classmethod
    def from_duckdb(cls, conn_or_path, sql_query=None, table_prefix=""):
        """
        Reconstructs a ResiResultSet by querying an existing DuckDB database.

        sql_query, if given, is run as-is to select rows from the results table,
        so it must come from a trusted source. table_prefix must be a plain SQL
        identifier prefix (letters, digits, underscore).
        """
        duckdb_table_names(table_prefix)
        if isinstance(conn_or_path, (str, Path)):
            conn = duckdb.connect(str(conn_or_path))
            close_conn = True
        else:
            conn = conn_or_path
            close_conn = False

        t_traces, t_results, t_rings, t_boards = duckdb_table_names(table_prefix)

        if sql_query:
            results_df = conn.execute(sql_query).df()
        else:
            results_df = conn.execute(f"SELECT * FROM {t_results}").df()

        if results_df.empty:
            if close_conn:
                conn.close()
            return cls()

        trace_ids = [int(x) for x in results_df['TraceID'].unique()]
        traces_df = conn.execute(f"SELECT * FROM {t_traces} WHERE list_contains(?, id)", [trace_ids]).df()

        result_ids = [int(x) for x in results_df['id'].unique()]
        rings_df = conn.execute(f"SELECT * FROM {t_rings} WHERE list_contains(?, ResultID)", [result_ids]).df()
        boards_df = conn.execute(f"SELECT * FROM {t_boards} WHERE list_contains(?, ResultID)", [result_ids]).df()

        result_set = cls()

        for _, res_row in results_df.iterrows():
            trace_id = res_row['TraceID']
            res_id = res_row['id']

            t_row_idx = traces_df[traces_df['id'] == trace_id]
            if t_row_idx.empty:
                continue
            t_row = t_row_idx.iloc[0]

            descriptors = {}
            for col in traces_df.columns:
                if col not in ('id', 'InsertTime', 'drill', 'feed', 'TraceHash'):
                    descriptors[col] = t_row[col]
            for col in results_df.columns:
                if col not in ('id', 'TraceID', 'rPos'):
                    descriptors[col] = res_row[col]

            rpos = res_row.get('rPos')
            drill = t_row.get('drill')
            feed = t_row.get('feed')

            r_rings = []
            if not rings_df.empty:
                r_rings = rings_df[rings_df['ResultID'] == res_id].to_dict(orient='records')

            r_boards = []
            if not boards_df.empty:
                r_boards = boards_df[boards_df['ResultID'] == res_id].to_dict(orient='records')

            result = ResiResult(
                filename=t_row['FileName'],
                descriptors=descriptors,
                drill=np.array(drill) if drill is not None else None,
                feed=np.array(feed) if feed is not None else None,
                rpos=np.array(rpos) if rpos is not None else None,
                ring_data=r_rings,
                board_moe=r_boards,
                resi_file=res_row['ResiFile']
            )
            result_set.results.append(result)

        if close_conn:
            conn.close()

        return result_set

    def to_deltalake(self, table_or_path, mode="merge", merge_key="FileName", schema=None, schema_mode="merge", storage_options=None, spark=None, lowercase_columns=False, column_mapping=None):
        """
        Merges or exports the result set records directly into a Delta Lake table.

        Supports BOTH PySpark notebook sessions in Microsoft Fabric (`spark`) AND
        pure Python environments (`deltalake` Rust-backed delta-rs engine).

        :param table_or_path: Path string, Path object, or existing DeltaTable instance.
        :param mode: 'merge' (upsert based on merge_key), 'append', or 'overwrite'.
        :param merge_key: Column name or tuple/list of column names to use as join predicate when mode='merge'.
        :param schema: Optional PyArrow or PySpark schema.
        :param schema_mode: Schema evolution mode ('merge' or 'overwrite') when appending.
        :param storage_options: Optional storage options dict (e.g. for Azure Lakehouse ABFSS or AWS S3).
        :param spark: Optional PySpark SparkSession instance. If None, automatically detects active PySpark session.
        :param lowercase_columns: If True, lowercases all column names and removes dots (e.g. TreeID->treeid, RPMCoef.a->rpmcoefa).
        :param column_mapping: Optional dict of source_col -> target_col mappings.
        :return: Updated DeltaTable or PySpark DeltaTable instance.
        """
        if not self.results:
            logger.warning("ResiResultSet is empty; nothing to write to Delta Lake.")
            return None

        # Build DataFrame with optional mangling (lowercasing, etc) and column mapping
        raw_records = [dict(r.descriptors) for r in self.results]
        if lowercase_columns or column_mapping:
            cleaned_records = []
            for rdict in raw_records:
                cdict = {}
                for k, v in rdict.items():
                    target_k = k
                    if lowercase_columns:
                        target_k = target_k.lower().replace(".", "")
                    if column_mapping and k in column_mapping:
                        target_k = column_mapping[k]
                    cdict[target_k] = v
                cleaned_records.append(cdict)
            pdf = pd.DataFrame(cleaned_records)
        else:
            pdf = pd.DataFrame(raw_records)

        # Ensure filename and tracefilename aliases are populated if either is present
        if "tracefilename" not in pdf.columns and "filename" in pdf.columns:
            pdf["tracefilename"] = pdf["filename"]
        if "filename" not in pdf.columns and "tracefilename" in pdf.columns:
            pdf["filename"] = pdf["tracefilename"]

        # If lowercase_columns is True and default merge_key 'FileName' is not present, auto-resolve merge_key
        if lowercase_columns and merge_key == "FileName" and "FileName" not in pdf.columns:
            if "tracefilename" in pdf.columns:
                merge_key = "tracefilename"
            elif "filename" in pdf.columns:
                merge_key = "filename"
            elif "inphash" in pdf.columns:
                merge_key = "inphash"

        # merge keys are interpolated into the merge predicate, so they must
        # be actual columns
        if mode == 'merge':
            keys = list(merge_key) if isinstance(merge_key, (list, tuple)) else [merge_key]
            missing = [k for k in keys if k not in pdf.columns]
            if not keys or missing:
                raise ValueError(f"merge_key must name columns of the data; not found: {missing or keys}")

        # Auto-detect active PySpark session if not explicitly passed
        if spark is None and 'pyspark' in sys.modules:
            try:
                from pyspark.sql import SparkSession
                spark = SparkSession.getActiveSession()
            except Exception:
                spark = None

        # If PySpark session is active, use PySpark native DeltaTable merge engine
        if spark is not None:
            from delta.tables import DeltaTable as PySparkDeltaTable

            spark_df = spark.createDataFrame(pdf)
            table_path_str = str(table_or_path)
            # Strip local Fabric POSIX mount prefix '/lakehouse/default/' if present,
            # because PySpark Java ABFS driver expects relative path e.g. 'Tables/...' or 'Files/...'
            if table_path_str.startswith("/lakehouse/default/"):
                table_path_str = table_path_str.replace("/lakehouse/default/", "")

            if isinstance(merge_key, (list, tuple)):
                predicate = " AND ".join([f"target.`{k}` = source.`{k}`" for k in merge_key])
            else:
                predicate = f"target.`{merge_key}` = source.`{merge_key}`"

            is_path = "/" in table_path_str or table_path_str.startswith("abfss://") or table_path_str.startswith(".")

            # Decide existence explicitly: a lookup error must never be read as
            # "no table", or the write below would replace the whole table
            pyspark_dt = None
            if is_path:
                table_exists = PySparkDeltaTable.isDeltaTable(spark, table_path_str)
            else:
                table_exists = spark.catalog.tableExists(table_path_str)
            if table_exists:
                pyspark_dt = (PySparkDeltaTable.forPath(spark, table_path_str) if is_path
                              else PySparkDeltaTable.forName(spark, table_path_str))

            from pyspark.sql.types import NullType, StringType

            target_schema_dict = {}
            if table_exists and pyspark_dt is not None:
                try:
                    target_schema_dict = {f.name: f.dataType for f in pyspark_dt.toDF().schema.fields}
                except Exception:
                    pass

            for field in spark_df.schema.fields:
                if isinstance(field.dataType, NullType):
                    if field.name in target_schema_dict:
                        spark_df = spark_df.withColumn(
                            field.name, spark_df[field.name].cast(target_schema_dict[field.name])
                        )
                    else:
                        spark_df = spark_df.withColumn(
                            field.name, spark_df[field.name].cast(StringType())
                        )

            if mode == 'overwrite' or not table_exists:
                # creating a new table must fail rather than replace whatever is there
                writer = spark_df.write.format("delta").mode(
                    "overwrite" if mode == 'overwrite' else "errorifexists"
                ).option(
                    "mergeSchema", "true" if schema_mode == "merge" else "false"
                )
                if is_path:
                    writer.save(table_path_str)
                else:
                    writer.saveAsTable(table_path_str)

                return DeltaMergeResult(
                    num_inserted=len(self.results),
                    num_updated=0,
                    metrics={'num_inserted': len(self.results), 'num_updated': 0}
                )

            if mode == 'append':
                writer = spark_df.write.format("delta").mode("append").option(
                    "mergeSchema", "true" if schema_mode == "merge" else "false"
                )
                if is_path:
                    writer.save(table_path_str)
                else:
                    writer.saveAsTable(table_path_str)

                return DeltaMergeResult(
                    num_inserted=len(self.results),
                    num_updated=0,
                    metrics={'num_inserted': len(self.results), 'num_updated': 0}
                )

            elif mode == 'merge':
                if schema_mode == 'merge':
                    try:
                        spark.conf.set("spark.databricks.delta.schema.autoMerge.enabled", "true")
                    except Exception:
                        pass
                    matching_cols = list(spark_df.columns)
                else:
                    try:
                        target_cols = set(pyspark_dt.toDF().columns)
                        matching_cols = [c for c in spark_df.columns if c in target_cols]
                    except Exception:
                        matching_cols = list(spark_df.columns)

                update_map = {f"`{c}`": f"source.`{c}`" for c in matching_cols}

                (
                    pyspark_dt.alias("target")
                    .merge(spark_df.alias("source"), predicate)
                    .whenMatchedUpdate(set=update_map)
                    .whenNotMatchedInsert(values=update_map)
                    .execute()
                )
                try:
                    last_op = pyspark_dt.history(1).collect()[0]
                    op_metrics = last_op.operationMetrics or {}
                    num_inserted = int(op_metrics.get('numTargetRowsInserted', 0))
                    num_updated = int(op_metrics.get('numTargetRowsUpdated', 0))
                except Exception:
                    op_metrics = {}
                    num_inserted = 0
                    num_updated = 0

                return DeltaMergeResult(
                    num_inserted=num_inserted,
                    num_updated=num_updated,
                    metrics=op_metrics
                )
            else:
                raise ValueError(f"Unsupported mode '{mode}'. Choose from 'merge', 'append', or 'overwrite'.")

        # Otherwise, use pure Python deltalake (delta-rs) + PyArrow
        import pyarrow as pa
        from deltalake import DeltaTable, write_deltalake

        arrow_tbl = pa.Table.from_pandas(pdf, preserve_index=False)

        if schema is not None:
            arrow_tbl = arrow_tbl.cast(schema)

        if isinstance(table_or_path, DeltaTable):
            table_path = table_or_path.table_uri
            table_exists = True
        else:
            # ask delta-rs rather than the local filesystem, so that file://,
            # abfss:// and s3:// tables are found too
            from deltalake.exceptions import TableNotFoundError
            table_path = str(table_or_path)
            try:
                DeltaTable(table_path, storage_options=storage_options)
                table_exists = True
            except TableNotFoundError:
                table_exists = False

        if mode == 'overwrite' or not table_exists:
            write_deltalake(
                table_path,
                arrow_tbl,
                # creating a new table must fail rather than replace whatever is there
                mode='overwrite' if mode == 'overwrite' else 'error',
                schema_mode=schema_mode,
                storage_options=storage_options
            )
            return DeltaMergeResult(
                num_inserted=len(self.results),
                num_updated=0,
                metrics={'num_inserted': len(self.results), 'num_updated': 0}
            )

        if mode == 'append':
            write_deltalake(
                table_path,
                arrow_tbl,
                mode='append',
                schema_mode=schema_mode,
                storage_options=storage_options
            )
            return DeltaMergeResult(
                num_inserted=len(self.results),
                num_updated=0,
                metrics={'num_inserted': len(self.results), 'num_updated': 0}
            )

        elif mode == 'merge':
            dt = table_or_path if isinstance(table_or_path, DeltaTable) else DeltaTable(table_path, storage_options=storage_options)

            if isinstance(merge_key, (list, tuple)):
                predicate = " AND ".join([f"target.{k} = source.{k}" for k in merge_key])
            else:
                predicate = f"target.{merge_key} = source.{merge_key}"

            merge_res = (
                dt.merge(
                    source=arrow_tbl,
                    predicate=predicate,
                    source_alias="source",
                    target_alias="target"
                )
                .when_matched_update_all()
                .when_not_matched_insert_all()
                .execute()
            )

            if isinstance(merge_res, dict):
                num_inserted = int(merge_res.get('num_target_rows_inserted', 0))
                num_updated = int(merge_res.get('num_target_rows_updated', 0))
                op_metrics = merge_res
            else:
                num_inserted = 0
                num_updated = 0
                op_metrics = {}

            return DeltaMergeResult(
                num_inserted=num_inserted,
                num_updated=num_updated,
                metrics=op_metrics
            )
        else:
            raise ValueError(f"Unsupported mode '{mode}'. Choose from 'merge', 'append', or 'overwrite'.")
            
