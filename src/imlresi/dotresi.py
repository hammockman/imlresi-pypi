    def to_dotresi(self, filepath, overwrite=False, resi_code=None, format_version="4.8.0"):
        """
        Saves the ResiResultSet to a .Resi file using the
        complete list structure and column schema required for Shiny compatibility.

        :param filepath: Target path for the .Resi file.
        :param overwrite: Whether to overwrite existing destination file or merge.
        :param resi_code: Optional instrument serial number override.
        :param format_version: Format version to generate ("4.8.0" for modern FWPA or "4.2.4" / "legacy" for older format).
        """
        filepath = Path(filepath)
        if filepath.parent:
            filepath.parent.mkdir(parents=True, exist_ok=True)

        fmt_ver = str(format_version).lower().strip()
        is_legacy = fmt_ver in ("4.2.4", "legacy", "v4.2.4")

        # Auto-detect format_version if not explicitly legacy and file exists with overwrite=False
        if filepath.exists() and not overwrite and format_version == "4.8.0":
            try:
                existing = ResiResultSet(filepath)
                if existing.version_info and any("4.2.4" in str(v) for v in existing.version_info.values()):
                    is_legacy = True
            except Exception:
                pass

        target_df_columns = LEGACY_DF_COLUMNS if is_legacy else DF_COLUMNS
        target_column_types = LEGACY_DF_COLUMN_TYPES if is_legacy else DF_COLUMN_TYPES

        # Merge existing data if file exists and we are not overwriting
        results_to_write = list(self.results)
        if is_legacy:
            version = ["Version 4.2.4"]
        else:
            version_info = { # copied directly from FWPA web app
                'platform': "x86_64-pc-linux-gnu",
                'arch': "x86_64",
                'os': "linux-gnu",
                'system': "x86_64, linux-gnu",
                'status': "",
                'major': "4",
                'minor': "6.0",
                'year': "2026",
                'month': "04",
                'day': "24",
                'svn rev': "89956",
                'language': "R",
                'version.string': "R version 4.6.0 (2026-04-24)",
                'nickname': "Because it was There",
            }
            version = list(version_info.values())[0]

        if filepath.exists() and not overwrite:
            existing = ResiResultSet(filepath)
            # Find which of existing results are NOT in self (by FileName)
            self_filenames = {r.FileName for r in self.results}
            merged_results = [r for r in existing.results if r.FileName not in self_filenames]
            results_to_write = merged_results + results_to_write

        # Reconstruct components from results_to_write
        df_rows = []
        res_traces = {}
        feed_traces = {}
        r_pos = {}
        den_traces = {}
        cum_den_traces = {}
        ring_rows = []
        board_rows = []
        rs_rows = []

        for r in results_to_write:
            fname = r.FileName

            # Reconstruct df row using case-insensitive descriptor lookups
            row = {col: None for col in target_df_columns}
            for col in target_df_columns:
                val = r.get_descriptor(col)
                if val is not None:
                    if target_column_types.get(col) == 'boolean':
                        if isinstance(val, str):
                            val = val.upper() not in ("FALSE", "F", "0")
                        else:
                            val = bool(val)
                    elif target_column_types.get(col) == 'float64':
                        val = clean_float(val)
                    row[col] = val
            row['FileName'] = fname

            if is_legacy:
                if not row.get('DBHOB'):
                    dob_val = r.get_descriptor('DOB') or r.get_descriptor('DBHOB')
                    if dob_val is not None:
                        row['DBHOB'] = clean_float(dob_val)

            if resi_code:
                row['ResiCode'] = resi_code
            if not row.get('ResiCode'):
                row['ResiCode'] = "PD500-0000"
            df_rows.append(row)

            # Reconstruct arrays
            if r.drill is not None:
                res_traces[fname] = r.drill
            if r.feed is not None:
                feed_traces[fname] = r.feed

            # Delimiter / Ring position vector array
            r_pos_val = r.rPos
            if r_pos_val is None:
                r_pos_val = r.get_descriptor('rPos')
            if r_pos_val is not None and len(r_pos_val) > 0:
                r_pos[fname] = r_pos_val

            # Computed density arrays (with fallback on-the-fly recomputation if missing)
            den_tr = getattr(r, 'den_trace', None)
            if den_tr is None and hasattr(r, 'recompute_den_trace'):
                try:
                    den_tr = r.recompute_den_trace()
                except Exception:
                    den_tr = None
            if den_tr is not None and len(den_tr) > 0:
                den_traces[fname] = den_tr

            cum_den_tr = getattr(r, 'cum_den_trace', None)
            if cum_den_tr is None and hasattr(r, 'recompute_cum_den_trace'):
                try:
                    cum_den_tr = r.recompute_cum_den_trace()
                except Exception:
                    cum_den_tr = None
            if cum_den_tr is not None and len(cum_den_tr) > 0:
                cum_den_traces[fname] = cum_den_tr

            # Reconstruct ring_data with key alias normalization
            for ring in r.ring_data:
                ring_row = {
                    'FileName': fname,
                    'TreeID': r.get_descriptor('TreeID', ''),
                    'ResiCode': r.get_descriptor('ResiCode', 'PD400-0000'),
                }
                for k, v in ring.items():
                    if k == 'RingMeanDen' and 'RingDensityMean' not in ring:
                        ring_row['RingDensityMean'] = clean_float(v)
                    elif k == 'RingMeanMOE' and 'RingMOEMean' not in ring:
                        ring_row['RingMOEMean'] = clean_float(v)
                    else:
                        ring_row[k] = clean_float(v) if k not in ('Radius', 'FileName', 'TreeID', 'ResiCode') else v
                ring_row_full = {col: None for col in RINGDATA_COLUMNS}
                ring_row_full.update(ring_row)
                ring_rows.append(ring_row_full)

            # Reconstruct board_moe with key alias normalization
            for board in r.board_moe:
                board_row = {
                    'FileName': fname,
                    'TreeID': r.get_descriptor('TreeID', ''),
                }
                moe_val = clean_float(board.get('MeanMOE') or board.get('BoardMOE') or board.get('boardMOE') or board.get('meanMOE'))
                if moe_val is not None:
                    board_row['MeanMOE'] = moe_val
                    board_row['BoardMOE'] = moe_val
                for k, v in board.items():
                    if k not in ('FileName', 'TreeID', 'MeanMOE', 'BoardMOE'):
                        board_row[k] = clean_float(v)
                board_row_full = {col: None for col in BOARDMOE_COLUMNS}
                board_row_full.update(board_row)
                board_rows.append(board_row_full)

            # Reconstruct rs_df row
            rs_row = {col: None for col in RSDF_COLUMNS}
            if getattr(r, 'rs_row', None):
                rs_row.update(r.rs_row)
            rs_row['FileName'] = fname
            rs_row['TreeID'] = r.get_descriptor('TreeID', '')
            rs_rows.append(rs_row)

        df_final = pd.DataFrame(df_rows) if df_rows else pd.DataFrame(columns=target_df_columns)
        rs_df = pd.DataFrame(rs_rows) if rs_rows else pd.DataFrame(columns=RSDF_COLUMNS)
        ring_data = pd.DataFrame(ring_rows) if ring_rows else pd.DataFrame(columns=RINGDATA_COLUMNS)
        board_moe = pd.DataFrame(board_rows) if board_rows else pd.DataFrame(columns=BOARDMOE_COLUMNS)

        if not den_traces:
            den_traces = None
        if not cum_den_traces:
            cum_den_traces = None

        # Apply strict typing schemas to the pandas DataFrames
        for col, dtype in target_column_types.items():
            if col in df_final.columns:
                df_final[col] = df_final[col].astype(dtype)

        for col, dtype in RINGDATA_COLUMN_TYPES.items():
            if col in ring_data.columns:
                ring_data[col] = ring_data[col].astype(dtype)

        # Convert all DataFrame objects to DataTable subclass so they serialize as R data.tables
        df_final_dt = DataTable(df_final)
        rs_df_dt = DataTable(rs_df) if rs_rows else None
        ring_data_dt = DataTable(ring_data)
        board_moe_dt = DataTable(board_moe) if board_rows else None

        # Write using rdata.write_rds with custom constructor dict
        from rdata.conversion.to_r import DEFAULT_CLASS_MAP
        custom_class_map = {DataTable: datatable_constructor}
        custom_class_map.update(DEFAULT_CLASS_MAP)

        resi_data = {
            'df': df_final_dt,
            'FRdf': None,
            'RSdf': rs_df_dt,
            'resTraces': res_traces,
            'feedTraces': feed_traces,
            'denTraces': den_traces,
            'cumDenTraces': cum_den_traces,
            'Tppl.Mean.Density': None,
            'ringData': ring_data_dt,
            'rPos': r_pos,
            'version': version,
            'boardMOE': board_moe_dt,
        }
        if not is_legacy:
            resi_data['regVar'] = None

        rdata.write_rds(str(filepath), resi_data, constructor_dict=custom_class_map)

    def load_traces(self, traces_or_files, api_uri, ctrlset=None, annotation=None):
        """
        Loads Trace objects or trace filenames, passes them through the API,
        converts them to ResiResult objects, and adds them to the result set.
        """
        from imlresi.trace import Trace

        # Normalize input to a list
        if isinstance(traces_or_files, (str, Path, Trace)):
            items = [traces_or_files]
        else:
            items = list(traces_or_files)

        for item in items:
            if isinstance(item, (str, Path)):
                path = normalize_filepath(item)
                trace = Trace()
                trace.read(str(path))
                trace.trace_filename = str(path)
            elif isinstance(item, Trace):
                trace = item
            else:
                raise TypeError(f"Unsupported trace/file type: {type(item)}")

            # Process using the Resi API
            res = trace.process_using_resiapi(api_uri, ctrlset=ctrlset, annotation=annotation)

            # Get filename
            fname = None
            if hasattr(trace, 'trace_filename') and trace.trace_filename:
                fname = Path(trace.trace_filename).name
            elif isinstance(trace.header, dict) and trace.header.get('comment'):
                fname = trace.header.get('comment')
            if not fname:
                fname = f"trace_{len(self.results) + 1}.rgp"

            # Parse the API response 'res'
            descriptors = {}
            for col in DF_COLUMNS:
                matched_key = next((k for k in res.keys() if k.lower() == col.lower()), None)
                if matched_key is not None:
                    val = res[matched_key]
                    if col == 'Standardised':
                        descriptors[col] = bool(val) if val is not None else True
                    elif col in NUMERIC_COLUMNS:
                        descriptors[col] = clean_float(val)
                    else:
                        descriptors[col] = val
                else:
                    descriptors[col] = None

            # Always ensure basic keys are not None if we can help it
            if not descriptors.get('FileName'):
                descriptors['FileName'] = fname
            if not descriptors.get('TreeID') and isinstance(trace.header, dict):
                descriptors['TreeID'] = trace.header.get('tree_id') or trace.header.get('remark') or ""

            # Ensure R defaults are populated if missing
            if not descriptors.get('TraceType'):
                descriptors['TraceType'] = 'B-B'  # Default trace type for processed traces
            if not descriptors.get('BaselineMethod'):
                descriptors['BaselineMethod'] = 'Linear'
            if not descriptors.get('RingMethod'):
                descriptors['RingMethod'] = 'Annual'

            # Parse ring data from ringData
            ring_data = []
            api_ring_data = res.get('ringData')
            if isinstance(api_ring_data, dict) and api_ring_data:
                # Find the first list in the dict to determine length
                any_val = next((v for v in api_ring_data.values() if isinstance(v, list)), None)
                if any_val:
                    n_rings = len(any_val)
                    for idx in range(n_rings):
                        ring_dict = {}
                        for col in RINGDATA_COLUMNS:
                            if col in ('FileName', 'TreeID', 'ResiCode'):
                                continue
                            if col in api_ring_data:
                                val_list = api_ring_data[col]
                                if idx < len(val_list):
                                    ring_dict[col] = clean_float(val_list[idx])
                        ring_data.append(ring_dict)

            # Parse board MOE and rs Summary Row
            board_moe = []
            api_board_moe = res.get('rsawmill', {}).get('boardMOE')
            if isinstance(api_board_moe, dict):
                any_val = next((v for v in api_board_moe.values() if isinstance(v, list)), None)
                if any_val:
                    n_boards = len(any_val)
                    for idx in range(n_boards):
                        board_dict = {}
                        for key in ('BoardMOE', 'MeanMOE', 'boardMOE', 'meanMOE'):
                            if key in api_board_moe:
                                val_list = api_board_moe[key]
                                if idx < len(val_list):
                                    board_dict['BoardMOE'] = clean_float(val_list[idx])
                                    break
                        if board_dict:
                            board_moe.append(board_dict)
            elif isinstance(api_board_moe, list):
                for val in api_board_moe:
                    try:
                        board_moe.append({'BoardMOE': clean_float(val)})
                    except Exception:
                        pass

            rs_row = {}
            api_board_summary = res.get('rsawmill', {}).get('boardSummary')
            if isinstance(api_board_summary, dict):
                for col in RSDF_COLUMNS:
                    if col in api_board_summary:
                        val_list = api_board_summary[col]
                        if val_list and len(val_list) > 0:
                            val = val_list[0]
                            if col not in ('FileName', 'TreeID', 'select'):
                                rs_row[col] = clean_float(val)
                            else:
                                rs_row[col] = str(val)

            # Reconstruct drill and feed data arrays
            drill = np.array(trace.drill).ravel().astype(float) if hasattr(trace, 'drill') and trace.drill is not None else np.array([], dtype=float)
            feed = np.array(trace.feed).ravel().astype(float) if hasattr(trace, 'feed') and trace.feed is not None else np.array([], dtype=float)
            rpos = clean_array(res.get('rPos') or res.get('rpos'))
            if rpos is None:
                rpos = np.array([], dtype=float)

            result = ResiResult(
                filename=fname,
                descriptors=descriptors,
                drill=drill,
                feed=feed,
                rpos=rpos,
                ring_data=ring_data,
                board_moe=board_moe,
                rs_row=rs_row
            )

            # Store precomputed arrays returned by R API if available
            result.den_trace = clean_array(res.get('denTraces') or res.get('denTrace'))
            result.cum_den_trace = clean_array(res.get('cumDenTraces') or res.get('cumDenTrace'))
            result.corr_trace = clean_array(res.get('cTrace') or res.get('corrTraces') or res.get('corrTrace'))

            self.results.append(result)

        return self

    def __len__(self):
        return len(self.results)

    def __getitem__(self, index):
        return self.results[index]

    def __iter__(self):
        return iter(self.results)

    def __repr__(self):
        return f"<ResiResultSet with {len(self.results)} records>"



