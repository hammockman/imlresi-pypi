def datatable_constructor(data, converter):
    """
    Custom rdata constructor that converts a DataTable to R c("data.table", "data.frame") class.
    """
    from rdata.parser import RObjectType
    from rdata.missing import R_INT_NA
    from rdata.conversion.to_r import convert_pd_array_to_np_array, build_r_object

    column_names = data.columns.to_numpy()
    r_value = []
    for column in column_names:
        series = data[column]
        pd_array = series.array
        if isinstance(pd_array, pd.Categorical):
            array = pd_array
        elif hasattr(pd_array, "to_numpy") and ("arrow" in type(pd_array).__name__.lower() or (hasattr(pd_array, "dtype") and "arrow" in str(pd_array.dtype).lower())):
            array = pd_array.to_numpy()
        else:
            array = convert_pd_array_to_np_array(pd_array)
        r_series = converter.convert_to_r_object(array)
        r_value.append(r_series)

    index = data.index
    if isinstance(index, pd.RangeIndex):
        assert isinstance(index.start, int)
        if (
            index.start == 1
            and index.stop == data.shape[0] + 1
            and index.step == 1
        ):
            row_names = np.ma.array(
                data=[R_INT_NA, -data.shape[0]],
                mask=[True, False],
                fill_value=R_INT_NA,
            )
        else:
            row_names = index
    elif isinstance(index, pd.Index):
        if (
            index.dtype == 'object'
            or np.issubdtype(str(index.dtype), np.integer)
        ):
            row_names = index.to_numpy()
        else:
            msg = f"pd.DataFrame pd.Index {index.dtype} not implemented"
            raise NotImplementedError(msg)
    else:
        msg = f"pd.DataFrame index {type(index)} not implemented"
        raise NotImplementedError(msg)

    # Use both data.table and data.frame classes
    r_attributes = converter.convert_to_r_attributes({
        'names': np.array(column_names, dtype=np.dtype('U')),
        'class': np.array(['data.table', 'data.frame'], dtype=np.dtype('U')),
        'row.names': row_names,
    })

    return build_r_object(
        RObjectType.VEC,
        value=r_value,
        is_object=True,
        attributes=r_attributes,
    )


def save_traces_to_dotresi(traces, filepath, append=True, resi_code=None, format_version="4.2.4"):
    """
    Saves or appends imlresi Trace objects to a .Resi file.
    Includes API computed results from trace._res if available.
    """
    if not isinstance(traces, (list, tuple, set)):
        traces = [traces]

    filepath = normalize_filepath(filepath)
    if filepath.parent:
        filepath.parent.mkdir(parents=True, exist_ok=True)

    rs = ResiResultSet()
    if filepath.exists() and append:
        rs.load(filepath)

    is_legacy = str(format_version).lower().strip() in ("4.2.4", "legacy", "v4.2.4")
    target_cols = LEGACY_DF_COLUMNS if is_legacy else DF_COLUMNS

    for trace in traces:
        fname = getattr(trace, 'trace_filename', None)
        if not fname and hasattr(trace, 'filename'):
            fname = getattr(trace, 'filename')
        if not fname and isinstance(trace.header, dict):
            fname = trace.header.get('FileName') or trace.header.get('filename')
        if fname:
            fname = Path(fname).name
        else:
            fname = f"trace_{len(rs.results) + 1}.rgp"

        tree_id = ""
        if isinstance(trace.header, dict):
            tree_id = trace.header.get('tree_id') or trace.header.get('remark') or ""
        if not tree_id and hasattr(trace, 'tree_id'):
            tree_id = trace.header.get('tree_id')

        comment_val = ""
        if isinstance(trace.header, dict):
            comment_val = trace.header.get('comment') or trace.header.get('Comment') or ""
        if not comment_val and hasattr(trace, 'comment'):
            comment_val = getattr(trace, 'comment') or ""

        # ResiCode
        trace_resi_code = None
        if resi_code:
            trace_resi_code = resi_code
        else:
            trace_resi_code = trace.get_instrument()
        if not trace_resi_code:
            trace_resi_code = "PD400-0000"

        feed_speed = float(trace.get_feedspeed()) * 10  # the trace's cm/min; .Resi files and FQResi use mm/min
        rpm = float(trace.get_rpm())

        sample_date = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        if isinstance(trace.header, dict):
            dt_val = trace.header.get('dateTime') or trace.header.get('date') or trace.header.get('datetime')
            if dt_val:
                sample_date = str(dt_val)

        standardised = True
        if isinstance(trace.header, dict) and 'Standardised' in trace.header:
            standardised = bool(trace.header['Standardised'])

        # Format arrays to flat 1D numeric vectors
        drill_data = np.array(trace.drill).ravel().astype(float) if hasattr(trace, 'drill') and trace.drill is not None else np.array([], dtype=float)
        feed_data = np.array(trace.feed).ravel().astype(float) if hasattr(trace, 'feed') and trace.feed is not None else np.array([], dtype=float)

        # Create descriptors dictionary
        trace_len_mm = len(drill_data) / 10.0
        descriptors = {col: None for col in target_cols}
        descriptors.update({
            'FileName': fname,
            'TreeID': tree_id,
            'ResiCode': trace_resi_code,
            'SampleDate': sample_date,
            'FeedSpeed': feed_speed,
            'RPM': rpm,
            'Standardised': standardised,
            'TraceType': 'B-B',
            'BaselineMethod': 'Linear',
            'RingMethod': 'Annual',
            'DBHOB': trace_len_mm,
            'UBDIA': trace_len_mm,
            'BarkThickness': 0.0,
            'EntryRadius': trace_len_mm / 2.0,
            'ExitRadius': trace_len_mm,
            'ExitBarkThickness': 0.0,
            'BLCorrDen': 0.0,
            'rSlope': 1.0,
            'rIntcpt': 0.0,
            'Comment': str(comment_val) if comment_val else "",
            'CheckStatus': 'TBD',
            'AdjustRecord': 'Auto',
            'EqnType': 'Linear',
        })

        # Overlay API computed results if trace was processed via ResiAPI
        api_res = getattr(trace, '_res', None) or getattr(trace, 'res', None)
        pos_data = np.array([], dtype=float)
        ring_data = []
        board_moe = []
        rs_row = {}

        if isinstance(api_res, dict) and api_res:
            for k in target_cols:
                if k in api_res and api_res[k] is not None:
                    descriptors[k] = api_res[k]

            # Sync specific API dict aliases
            if 'RPMCoef.a' in api_res:
                descriptors['RPMCoef'] = api_res['RPMCoef.a']

            pos_data = clean_array(api_res.get('rPos') or api_res.get('rpos'))
            if pos_data is None:
                pos_data = np.array([], dtype=float)

            # Ring data
            api_ring_data = api_res.get('ringData')
            if isinstance(api_ring_data, dict) and api_ring_data:
                any_val = next((v for v in api_ring_data.values() if isinstance(v, list)), None)
                if any_val:
                    n_rings = len(any_val)
                    for idx in range(n_rings):
                        ring_dict = {}
                        for col in RINGDATA_COLUMNS:
                            if col in ('FileName', 'TreeID', 'ResiCode'):
                                continue
                            if col in api_ring_data:
                                val_list = api_ring_data[col]
                                if idx < len(val_list):
                                    ring_dict[col] = clean_float(val_list[idx])
                        ring_data.append(ring_dict)

            # Board MOE
            api_board_moe = api_res.get('rsawmill', {}).get('boardMOE') if isinstance(api_res.get('rsawmill'), dict) else None
            if isinstance(api_board_moe, dict):
                any_val = next((v for v in api_board_moe.values() if isinstance(v, list)), None)
                if any_val:
                    n_boards = len(any_val)
                    for idx in range(n_boards):
                        board_dict = {}
                        for key in ('BoardMOE', 'MeanMOE', 'boardMOE', 'meanMOE'):
                            if key in api_board_moe:
                                val_list = api_board_moe[key]
                                if idx < len(val_list):
                                    board_dict['BoardMOE'] = clean_float(val_list[idx])
                                    break
                        if board_dict:
                            board_moe.append(board_dict)

            # RS board summary row
            api_board_summary = api_res.get('rsawmill', {}).get('boardSummary') if isinstance(api_res.get('rsawmill'), dict) else None
            if isinstance(api_board_summary, dict):
                for col in RSDF_COLUMNS:
                    if col in api_board_summary:
                        val_list = api_board_summary[col]
                        if val_list and len(val_list) > 0:
                            val = val_list[0]
                            if col not in ('FileName', 'TreeID', 'select'):
                                rs_row[col] = clean_float(val)
                            else:
                                rs_row[col] = str(val)

        result = ResiResult(
            filename=fname,
            descriptors=descriptors,
            drill=drill_data,
            feed=feed_data,
            rpos=pos_data,
            ring_data=ring_data,
            board_moe=board_moe,
            rs_row=rs_row
        )

        if isinstance(api_res, dict) and api_res:
            result.den_trace = clean_array(api_res.get('denTraces') or api_res.get('denTrace'))
            result.cum_den_trace = clean_array(api_res.get('cumDenTraces') or api_res.get('cumDenTrace'))
            result.corr_trace = clean_array(api_res.get('cTrace') or api_res.get('corrTraces') or api_res.get('corrTrace'))

        rs.results.append(result)

    rs.to_dotresi(filepath, overwrite=True, resi_code=resi_code, format_version=format_version)

def main(args=None):
    """
    Command line interface driver for writing raw trace files into a .Resi file.
    """
    import argparse
    import sys
    from imlresi.trace import Trace

    parser = argparse.ArgumentParser(
        description="Convert a list of raw IML trace files into a combined .Resi file."
    )
    parser.add_argument(
        "trace_files",
        nargs="+",
        help="One or more raw IML trace files (e.g. .rgp, .json, .txt) to combine."
    )
    parser.add_argument(
        "-o", "--output",
        required=True,
        help="Path to the output .Resi file."
    )
    parser.add_argument(
        "-r", "--resicode",
        default=None,
        help="Optional licensed Resi serial number override (e.g. PD400-0000)."
    )

    parsed_args = parser.parse_args(args)

    traces = []
    for filepath_str in parsed_args.trace_files:
        path = Path(filepath_str)
        if not path.exists():
            print(f"Error: File '{path}' does not exist. Skipping.")
            continue
        try:
            trace = Trace()
            trace.read(str(path))
            traces.append(trace)
            print(f"Successfully read trace: {path.name}")
        except Exception as e:
            print(f"Error: Failed to read trace '{path.name}' ({e}). Skipping.")

    if not traces:
        print("No traces successfully read. Exiting.")
        sys.exit(1)

    print(f"Saving {len(traces)} traces to '{parsed_args.output}'...")
    try:
        save_traces_to_dotresi(traces, parsed_args.output, resi_code=parsed_args.resicode)
        print("Traces written successfully!")
    except Exception as e:
        print(f"Error writing to output file: {e}")
        sys.exit(1)

def change_instrument_id(dotresi_filepath, new_instrument_id, output_filepath=None, overwrite=True, format_version="4.8.0"):
    """
    Loads a .Resi file, updates the instrument ID (ResiCode / toolserial) for all results in the set,
    and saves the modified result set back to disk.

    :param dotresi_filepath: Path to the input .Resi file (supports abfss:, file:, or local paths).
    :param new_instrument_id: New instrument ID string (e.g. 'PD500-0755').
    :param output_filepath: Optional path to save the modified .Resi file. If None, overwrites input file.
    :param overwrite: Whether to overwrite target output file if it exists. Default True.
    :param format_version: Format version to generate ("4.8.0" for modern FWPA or "4.2.4" / "legacy" for older format).
    :return: ResiResultSet with updated instrument IDs.
    """
    filepath = normalize_filepath(dotresi_filepath)
    out_path = normalize_filepath(output_filepath) if output_filepath is not None else filepath

    rs = ResiResultSet(filepath)
    rs.set_instrument_id(new_instrument_id)
    rs.to_dotresi(out_path, overwrite=overwrite, resi_code=new_instrument_id, format_version=format_version)
    return rs


